#!/usr/bin/env python3
"""Polyhex realizations of Mann's marked hexapillars (Track B construction experiment).

Mann (Amer. Math. Monthly 111 (2004), Figure 5, Theorem 1): an n-hexapillar is n regular
hexagons in a row, its edges marked with congruent, centred bumps and nicks: both upper edges
of every hexagon nicked, both lower edges bumped, the outer end on one side flat and on the
other nicked. H = 4 for n = 2, 3 and H = 5 for n >= 4 (marked tile, continuous plane).

Here each hexagon becomes a "macro-hexagon": the polyhex of all cells within hex distance k-1 of
a centre (3k^2-3k+1 cells). Macro-hexagons tile the plane by translations of the lattice
generated by v = (2k-1, -(k-1)) and its 60-degree rotations (Kaplan's axial coordinates). A
macro-edge's midpoint is the midpoint of a cell edge between a cell a of one macro-hexagon and
a cell b of its neighbour. A bump adds b; a nick removes a. So a bump meets a nick exactly,
bump meets bump overlaps, nick meets nick leaves a gap, and flat meets either misfits, as with
Mann's markings. Whether the polyhex keeps Mann's Heesch numbers is an experiment: unlike the
continuous tile, a polyhex also has unintended placements (macro-hexagons offset by single
cells, either lattice chirality), which can add or remove coronas.

Usage:
  python3 halo/hexapillar.py --k 2 3 --n 2 3 4 5            # print shapes (heesch-sat lines)
  python3 halo/hexapillar.py --k 2 --n 2 3 4 5 --check      # also classify with heesch-sat
"""
import argparse
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shape as shp  # noqa: E402

NB = shp.NEIGHBOURS["H"]


def dist(p):
    x, y = p
    return max(abs(x), abs(y), abs(x + y))


def rot(p):
    """60-degree rotation in Kaplan's axial coordinates (as in shape.SYMMETRIES)."""
    x, y = p
    return (-y, x + y)


def macro_hex(c, k):
    cx, cy = c
    r = k - 1
    return {(cx + x, cy + y) for x in range(-r, r + 1) for y in range(-r, r + 1) if dist((x, y)) <= r}


def lattice(k):
    """The six neighbour vectors u0..u5 (u_{j+1} = rot(u_j)) of the macro-hexagon tiling."""
    u = [(2 * k - 1, -(k - 1))]
    for _ in range(5):
        u.append(rot(u[-1]))
    return u


def check_tiling(k, radius=3):
    """Macro-hexagons at lattice points within `radius` steps must be disjoint and cover the
    central region with no gap."""
    u = lattice(k)
    centres = {(0, 0)}
    for _ in range(radius):
        centres |= {(c[0] + v[0], c[1] + v[1]) for c in centres for v in u}
    owner = {}
    for c in centres:
        for p in macro_hex(c, k):
            if p in owner:
                return False, f"overlap at {p}"
            owner[p] = c
    inner = 2 * k  # every cell this close to the centre must be covered
    for x in range(-3 * inner, 3 * inner + 1):
        for y in range(-3 * inner, 3 * inner + 1):
            if dist((x, y)) <= inner and (x, y) not in owner:
                return False, f"gap at {(x, y)}"
    return True, f"{len(centres)} macro-hexagons tile without overlap or gap"


def edge_cells(c, u, k):
    """The cell pair (a in the macro-hexagon at c, b in its neighbour at c+u) whose shared cell
    edge has its midpoint at the macro-edge midpoint c + u/2."""
    own, other = macro_hex(c, k), macro_hex((c[0] + u[0], c[1] + u[1]), k)
    two_m = (2 * c[0] + u[0], 2 * c[1] + u[1])
    pairs = []
    for a in own:
        b = (two_m[0] - a[0], two_m[1] - a[1])
        if b in other and (b[0] - a[0], b[1] - a[1]) in NB:
            pairs.append((a, b))
    if len(pairs) != 1:
        raise ValueError(f"macro-edge midpoint is not a single cell-edge midpoint (k={k}, pairs={pairs})")
    return pairs[0]


def hexapillar(n, k, top=(1, 2), bottom=(4, 5), end_flat=3, end_nick=0):
    """Cells of the n-hexapillar on side-k macro-hexagons. The chain runs along u0; edges
    `top` are nicked and `bottom` bumped on every macro-hexagon; the first hexagon's edge
    `end_flat` is flat and the last one's edge `end_nick` is nicked."""
    u = lattice(k)
    centres = [(i * u[0][0], i * u[0][1]) for i in range(n)]
    cells = set()
    for c in centres:
        cells |= macro_hex(c, k)
    bumps, nicks = set(), set()
    for i, c in enumerate(centres):
        for j in top:
            nicks.add(edge_cells(c, u[j], k)[0])
        for j in bottom:
            bumps.add(edge_cells(c, u[j], k)[1])
        if i == n - 1:
            nicks.add(edge_cells(c, u[end_nick], k)[0])
    assert not (bumps & cells), "a bump landed inside the chain"
    return sorted((cells | bumps) - nicks), len(bumps), len(nicks)


# --- triangle-grid (heesch-sat grid I) realization ------------------------------------------
# heesch-sat's sparse I coordinates: triangle centres (x, y) with x % 3 in {0, 1} and
# y % 3 == x % 3; Cartesian position (x + y/2, y*sqrt(3)/2). Vertices have x, y = 2 (mod 3).

TRI_VERTS = {0: [(-1, -1), (-1, 2), (2, -1)], 1: [(1, 1), (-2, 1), (1, -2)]}


def tri_neighbours(t):
    x, y = t
    v = TRI_VERTS[x % 3]
    return [(x + v[i][0] + v[j][0], y + v[i][1] + v[j][1]) for i, j in ((0, 1), (0, 2), (1, 2))]


def tri_sectors(V):
    """The six triangles around vertex V, keyed by outward direction in degrees (30, 90, ... 330)."""
    import math
    out = {}
    for dx in range(-2, 3):
        for dy in range(-2, 3):
            t = (V[0] + dx, V[1] + dy)
            if t[0] % 3 not in (0, 1) or t[1] % 3 != t[0] % 3:
                continue
            if V in [(t[0] + a, t[1] + b) for a, b in TRI_VERTS[t[0] % 3]]:
                cx, cy = dx + dy / 2, dy * math.sqrt(3) / 2
                out[round(math.degrees(math.atan2(cy, cx))) % 360] = t
    assert len(out) == 6, out
    return out


def tri_outside(t, V):
    """The triangle across t's edge that does not touch the vertex V."""
    x, y = t
    verts = [(x + a, y + b) for a, b in TRI_VERTS[x % 3]]
    i, j = [k for k in range(3) if verts[k] != V]
    return (verts[i][0] + verts[j][0] - x, verts[i][1] + verts[j][1] - y)


def iamond_hexapillar(n):
    """Side-1 hexagons along direction 30 degrees; sector directions 30 (E, toward the next
    hexagon), 90 and 150 (upper edges: nicks), 210 (W: flat on the first hexagon),
    270 and 330 (lower edges: bumps); the last hexagon's E sector is nicked."""
    centres = [(2 + 3 * i, -1 + 3 * i) for i in range(n)]
    cells, bumps, nicks = set(), set(), set()
    for i, V in enumerate(centres):
        sec = tri_sectors(V)
        cells |= set(sec.values())
        nicks |= {sec[90], sec[150]}
        bumps |= {tri_outside(sec[270], V), tri_outside(sec[330], V)}
        if i == n - 1:
            nicks.add(sec[30])
    assert not (bumps & cells)
    return sorted((cells | bumps) - nicks), len(bumps), len(nicks)


def tri_connected(cells):
    s = set(cells)
    seen, stack = {cells[0]}, [cells[0]]
    while stack:
        for q in tri_neighbours(stack.pop()):
            if q in s and q not in seen:
                seen.add(q)
                stack.append(q)
    return len(seen) == len(s)


def tri_best_spans(cells):
    best = None
    for a, b, d, e in shp.SYMMETRIES["H"]:
        pts = [(a * x + b * y, d * x + e * y) for x, y in cells]
        sx, sy = shp.spans(pts)
        if best is None or sx + sy < best[0] + best[1]:
            best = (sx, sy)
    return best


def classify(line, maxlevel=7, timeout=3600, mem_mb=48000):
    import runner
    opts = argparse.Namespace(sat=runner.DEFAULT_SAT, maxlevel=maxlevel, timeout=timeout, timeout_long=timeout,
                              mem_mb=mem_mb, periodic_budget=60.0, periodic_quick=10.0, periodic_max_t=24,
                              escalate_maxlevel=0)
    return runner.classify(line, opts, tempfile.mkdtemp(prefix="halo_hexapillar_"))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--grid", default="H", choices=["H", "I"],
                    help="H: macro-hexagons of hex cells (side k); I: side-1 hexagons of 6 triangles")
    ap.add_argument("--k", type=int, nargs="+", default=[2, 3])
    ap.add_argument("--n", type=int, nargs="+", default=[2, 3, 4, 5])
    ap.add_argument("--check", action="store_true", help="classify each shape with heesch-sat (runner.classify)")
    ap.add_argument("--maxlevel", type=int, default=7)
    ap.add_argument("--timeout", type=float, default=3600)
    ap.add_argument("--mem-mb", type=float, default=48000)
    ap.add_argument("--out", default="", help="append JSONL results here")
    args = ap.parse_args()
    if args.grid == "I":
        for n in args.n:
            cells, nb, nn = iamond_hexapillar(n)
            line = "I " + " ".join(f"{x} {y}" for x, y in cells)
            sx, sy = tri_best_spans(cells)
            row = {"construction": "mann-hexapillar-iamond-side1", "n": n, "bumps": nb, "nicks": nn,
                   "cells": len(cells), "connected": tri_connected(cells), "span_x": sx, "span_y": sy,
                   "limits_ok": len(cells) <= 200 and sx + sy <= 29, "mann_H": 4 if n in (2, 3) else 5, "line": line}
            print(f"  n={n}: {len(cells)} triangles, {nb} bumps, {nn} nicks, connected {row['connected']}, best spans "
                  f"{sx}+{sy}={sx + sy}, limits {'ok' if row['limits_ok'] else 'EXCEEDED'}; Mann H={row['mann_H']}",
                  flush=True)
            print(f"    {line}", flush=True)
            if args.check:
                rec = classify(line, args.maxlevel, args.timeout, args.mem_mb)
                rec.pop("record", None)
                row.update({k2: rec.get(k2) for k2 in ("status", "hc", "hh", "seconds", "peak_rss_mb", "stop")})
                print(f"    heesch-sat: {row['status']} hc={row['hc']} hh={row['hh']} "
                      f"({row['seconds']} s, {row['peak_rss_mb']} MB)", flush=True)
            if args.out:
                with open(args.out, "a") as fh:
                    fh.write(json.dumps(row) + "\n")
        return
    for k in args.k:
        ok, msg = check_tiling(k)
        print(f"k={k}: macro-hexagon of {len(macro_hex((0, 0), k))} cells; lattice u0={lattice(k)[0]}; {msg}",
              flush=True)
        if not ok:
            continue
        for n in args.n:
            cells, nb, nn = hexapillar(n, k)
            line = shp.canonical("H", cells)
            okc, problems, info = shp.check(line)
            row = {"construction": "mann-hexapillar-polyhex", "k": k, "n": n, "bumps": nb, "nicks": nn,
                   "cells": len(cells), "span_x": info["span_x"], "span_y": info["span_y"],
                   "limits_ok": okc and not any("stricter" in p for p in problems), "problems": problems,
                   "mann_H": 4 if n in (2, 3) else 5, "canon": line}
            print(f"  n={n}: {len(cells)} cells, {nb} bumps, {nn} nicks, spans {info['span_x']}+{info['span_y']}, "
                  f"limits {'ok' if row['limits_ok'] else problems}; Mann H={row['mann_H']}", flush=True)
            print(f"    {line}", flush=True)
            if args.check and row["limits_ok"]:
                rec = classify(line, args.maxlevel, args.timeout, args.mem_mb)
                rec.pop("record", None)
                row.update({k2: rec.get(k2) for k2 in ("status", "hc", "hh", "seconds", "peak_rss_mb", "stop")})
                print(f"    heesch-sat: {row['status']} hc={row['hc']} hh={row['hh']} "
                      f"({row['seconds']} s, {row['peak_rss_mb']} MB)", flush=True)
            if args.out:
                with open(args.out, "a") as fh:
                    fh.write(json.dumps(row) + "\n")


if __name__ == "__main__":
    main()
